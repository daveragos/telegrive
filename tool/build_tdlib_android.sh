#!/usr/bin/env bash
#
# Builds TDLib for Android into android/app/src/main/jniLibs.
#
# handy_tdlib's libtdjson.so, libcrypto.so and libssl.so are aligned for 4 KB
# memory pages, which phones with 16 KB pages run only in a compatibility mode
# and Google Play no longer accepts. This builds the same TDLib commit with
# segments aligned for 16 KB pages, and with OpenSSL linked in, so the app
# carries one libtdjson.so per ABI and no libcrypto.so or libssl.so. The app
# packages these in place of handy_tdlib's (see android/app/build.gradle.kts).
#
# It needs the Android NDK, CMake and gperf, and takes a while. Run it again
# after changing TD_COMMIT, OPENSSL_VERSION or NDK_VERSION.
set -euo pipefail

# The commit handy_tdlib's Dart API was generated from (TDLib 1.8.36). Keep
# the two in step: a different TDLib can send objects the Dart side cannot
# parse, or reject requests it builds.
TD_COMMIT=87d881071fe514936bb17029e96761141287d2be

OPENSSL_VERSION=3.5.9
OPENSSL_SHA256=603f5602e2eef00d77fbd429d34dcd5822bb301757a1bc9cdb24c670f1eb859a

# The NDK the app builds with (flutter.ndkVersion). r28 and newer align
# shared libraries for 16 KB pages; the linker flag below says so for every
# ABI either way.
NDK_VERSION=28.2.13676358

# The app's minSdk (flutter.minSdkVersion).
MIN_SDK=24

ABIS="arm64-v8a armeabi-v7a x86_64 x86"

root="$(cd "$(dirname "$0")/.." && pwd)"
work="$root/build/tdlib-android"
out="$root/android/app/src/main/jniLibs"
jobs="$(sysctl -n hw.ncpu 2> /dev/null || nproc)"

# The SDK's copy of NDK_VERSION, or ANDROID_NDK_ROOT when that is the same
# version.
sdk="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-$HOME/Library/Android/sdk}}"
ndk="$sdk/ndk/$NDK_VERSION"
[ -d "$ndk" ] || ndk="${ANDROID_NDK_ROOT:-${ANDROID_NDK_HOME:-}}"
if ! grep -q "^Pkg.Revision = $NDK_VERSION\$" "$ndk/source.properties" 2> /dev/null; then
  echo "NDK $NDK_VERSION is required: sdkmanager \"ndk;$NDK_VERSION\"" >&2
  exit 1
fi
toolchain="$(echo "$ndk"/toolchains/llvm/prebuilt/*)"

for tool in cmake gperf make perl; do
  command -v "$tool" > /dev/null || { echo "$tool is required" >&2; exit 1; }
done

page_flags="-Wl,-z,max-page-size=16384 -Wl,-z,common-page-size=16384"

mkdir -p "$work"
cd "$work"

# Sources.
if [ ! -d td ]; then
  git clone https://github.com/tdlib/td.git td
fi
git -C td cat-file -e "$TD_COMMIT^{commit}" 2> /dev/null || git -C td fetch origin
git -C td checkout -q "$TD_COMMIT"

openssl_tar="openssl-$OPENSSL_VERSION.tar.gz"
if [ ! -f "$openssl_tar" ]; then
  curl -fL -o "$openssl_tar.part" \
    "https://github.com/openssl/openssl/releases/download/openssl-$OPENSSL_VERSION/$openssl_tar"
  mv "$openssl_tar.part" "$openssl_tar"
fi
echo "$OPENSSL_SHA256  $openssl_tar" | shasum -a 256 -c -

# Part of TDLib's source is generated by tools built for this machine.
cmake -S td -B native -DCMAKE_BUILD_TYPE=Release \
  -DTD_GENERATE_SOURCE_FILES=ON -DCMAKE_POLICY_VERSION_MINIMUM=3.5
cmake --build native --target prepare_cross_compiling -j "$jobs"

# $1: ABI.
build_openssl() {
  local prefix="$work/openssl-$1"
  [ -f "$prefix/lib/libcrypto.a" ] && return
  local target extra=""
  case "$1" in
    arm64-v8a) target=android-arm64 ;;
    # ARMv8 crypto instructions on 64-bit CPUs running 32-bit apps, chosen at
    # run time.
    armeabi-v7a) target=android-arm extra=-D__ARM_MAX_ARCH__=8 ;;
    x86_64) target=android-x86_64 ;;
    x86) target=android-x86 ;;
  esac
  local src="$work/openssl-src-$1"
  rm -rf "$src"
  mkdir -p "$src"
  tar xzf "$openssl_tar" -C "$src" --strip-components 1
  (
    cd "$src"
    export ANDROID_NDK_ROOT="$ndk"
    export PATH="$toolchain/bin:$PATH"
    # Position-independent, since it ends up inside a shared library.
    ./Configure "$target" no-shared no-tests no-apps no-docs no-engine \
      no-async -D__ANDROID_API__="$MIN_SDK" -fPIC $extra \
      -ffunction-sections -fdata-sections \
      --prefix="$prefix" --libdir=lib
    make -j "$jobs" build_libs
    make install_dev
  )
}

# Optimised for size with ThinLTO, as handy_tdlib's own builds are: at -O3
# the library comes out half as large again.
# $1: ABI.
build_td() {
  local ssl="$work/openssl-$1"
  cmake -S td -B "td-$1" \
    -DCMAKE_TOOLCHAIN_FILE="$ndk/build/cmake/android.toolchain.cmake" \
    -DANDROID_ABI="$1" \
    -DANDROID_PLATFORM="android-$MIN_SDK" \
    -DANDROID_STL=c++_static \
    -DCMAKE_BUILD_TYPE=MinSizeRel \
    -DCMAKE_C_FLAGS_MINSIZEREL="-Oz -DNDEBUG" \
    -DCMAKE_CXX_FLAGS_MINSIZEREL="-Oz -DNDEBUG" \
    -DTD_ENABLE_LTO=ON \
    -DCMAKE_POLICY_VERSION_MINIMUM=3.5 \
    -DCMAKE_SHARED_LINKER_FLAGS="$page_flags" \
    -DOPENSSL_FOUND=1 \
    -DOPENSSL_INCLUDE_DIR="$ssl/include" \
    -DOPENSSL_CRYPTO_LIBRARY="$ssl/lib/libcrypto.a" \
    -DOPENSSL_SSL_LIBRARY="$ssl/lib/libssl.a" \
    -DOPENSSL_LIBRARIES="$ssl/lib/libssl.a;$ssl/lib/libcrypto.a"
  cmake --build "td-$1" --target tdjson -j "$jobs"
  mkdir -p "$out/$1"
  "$toolchain/bin/llvm-strip" --strip-unneeded \
    -o "$out/$1/libtdjson.so" "td-$1/libtdjson.so"
}

# Every loadable segment starts on a 16 KB boundary, and nothing but the
# system's own libraries is needed beside it.
# $1: ABI.
check_td() {
  local lib="$out/$1/libtdjson.so"
  local readelf="$toolchain/bin/llvm-readelf"
  local align
  for align in $("$readelf" -lW "$lib" | awk '$1 == "LOAD" { print $NF }'); do
    if (( align < 16384 )); then
      echo "$lib has a segment aligned to $align, below 16 KB" >&2
      exit 1
    fi
  done
  if "$readelf" -dW "$lib" | grep -E 'NEEDED|TEXTREL' |
    grep -qE 'libcrypto|libssl|c\+\+_shared|TEXTREL'; then
    echo "$lib needs a library the app does not carry, or patches its code" >&2
    exit 1
  fi
}

for abi in $ABIS; do
  build_openssl "$abi"
  build_td "$abi"
  check_td "$abi"
done
echo "Built libtdjson.so for $ABIS in $out"
